/**
 * Emberwake: case-study assets for the scroll-driven illustrated story.
 *
 * These are captures of the live piece, not design exports: the WebGL output is
 * the deliverable, so the frames are screenshots of Emberwake's production
 * build (1440x900 at 2x, and a 390px phone at 2x), taken with Playwright on
 * 2026-11-05. `reinked` is the one composite: the raw Doré scan on the left,
 * the same frame as the shader draws it on the right. Masters and the capture
 * notes are in assets-src/work/emberwake/.
 *
 * Unlike the other sets these are AVIF, with a single 1200px WebP fallback:
 * engraved hatching under a line screen is close to worst-case content for
 * lossy WebP (see AVIF_PROJECTS in scripts/build-work-images.mjs).
 */
type Scene =
  | "burning"
  | "reinked"
  | "gate"
  | "woke"
  | "melt"
  | "panels"
  | "iris"
  | "static"
  | "phone-burning"
  | "contents";

/** Phone captures: shown at phone width in the case study, not column width. */
const PHONE_SCENES: ReadonlySet<Scene> = new Set(["phone-burning"]);

/**
 * Intrinsic size of each 2400px output, generated by
 * scripts/build-work-images.mjs. Typed as Record<Scene, …>, so a scene with no
 * generated image is a compile error rather than a broken frame.
 */
const DIMENSIONS: Record<Scene, { w: number; h: number }> = sizes.emberwake;

type EmberwakeAssetProps = {
  scene: Scene;
  className?: string;
  /** Accessible description of the frame. Empty string renders it decorative. */
  alt: string;
  /**
   * The Work-grid card passes 16/9 for a uniform thumbnail. The frames are
   * 16:10 with the subject mid-frame, so the crop is centered, not top-anchored
   * like the full-page captures in the other sets.
   */
  ratio?: number;
};

/**
 * Every frame is lazy, the cover included — unlike Lumin's eager,
 * high-priority cover. Measured on 2026-11-05 against a production build:
 *
 *   - The LCP element is the h1 on both a 1440x900 desktop and a 412px phone
 *     (PerformanceObserver, five runs each, ~100ms). The title runs to two
 *     lines on desktop and five on a phone, which pushes most of the cover
 *     below the first screen, so the image never wins LCP.
 *   - Fetched eagerly, the cover's AVIF decode landed on the simulated 4x-CPU
 *     critical path and put Lighthouse's LCP ~50ms over the ratchet in
 *     scripts/lh-gate.mjs (3490ms vs 3450), whatever its priority or bytes.
 *     Lazy, it measures ~3190ms.
 *
 * If the title or summary gets much shorter, re-check: the cover could move
 * into the first screen and become the LCP element, and then it should be
 * eager again.
 */
export function EmberwakeAsset({
  scene,
  className,
  alt,
  ratio,
}: EmberwakeAssetProps) {
  const { w, h } = DIMENSIONS[scene];
  const base = `/work/emberwake/${scene}`;
  // A card passes a ratio and wants the uniform crop, phone frame or not.
  const phone = !ratio && PHONE_SCENES.has(scene);
  const sizesAttr = ratio ? CARD_SIZES : phone ? PHONE_SIZES : CASE_STUDY_SIZES;

  return (
    // `contents` so the <img> keeps its place in the parent's layout and the
    // caller's className (margins, rounding, width) applies to it directly.
    <picture className="contents">
      <source type="image/avif" srcSet={workAvifSrcSet(base, w)} sizes={sizesAttr} />
      {/* Raw <img>, not next/image — see src/lib/workImages.ts. The src is
          the WebP fallback for browsers without AVIF. (No lint disable
          needed: no-img-element allows an <img> inside a <picture>.) */}
      <img
        src={`${base}-1200.webp`}
        alt={alt}
        width={w}
        height={h}
        loading="lazy"
        decoding="async"
        style={{ aspectRatio: ratio ?? `${w} / ${h}` }}
        className={cn(
          // bg-ink, not surface-raised: every frame is a dark plate, so the
          // box a lazy image reserves shouldn't flash white first.
          "block w-full bg-ink shadow-soft",
          ratio ? "object-cover" : "object-contain",
          className,
          // After className so it narrows the case study's w-full.
          phone && "mx-auto max-w-sm",
        )}
      />
    </picture>
  );
}

